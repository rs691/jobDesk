using Microsoft.Extensions.Options;

namespace JobDesk.Storage;

// Default for F5: files go to JobDesk/App_Data/uploads. That folder is outside
// wwwroot, so files are only reachable through the controller, like a private bucket.
public class LocalFileStorage : IFileStorage
{
    private readonly string _root;
    private readonly string _displayPath;

    public LocalFileStorage(IOptions<StorageOptions> options, IWebHostEnvironment env)
    {
        _displayPath = options.Value.LocalPath;
        _root = Path.GetFullPath(Path.Combine(env.ContentRootPath, _displayPath));
        Directory.CreateDirectory(_root);
    }

    public string ProviderName => $"Local folder ({_displayPath})";

    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken ct = default)
    {
        var path = ResolvePath(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = File.Create(path);
        await content.CopyToAsync(file, ct);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken ct = default)
    {
        var path = ResolvePath(key);
        return Task.FromResult<Stream?>(File.Exists(path) ? File.OpenRead(path) : null);
    }

    public Task DeleteAsync(string key, CancellationToken ct = default)
    {
        var path = ResolvePath(key);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }

    // Keys are generated by AttachmentService, but never trust a path: block "../" escapes.
    private string ResolvePath(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_root, key));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidOperationException("Storage key resolves outside the upload folder.");
        return path;
    }
}
